CREATE TABLE IF NOT EXISTS locations (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    x                   INTEGER NOT NULL,
    y                   DOUBLE PRECISION NOT NULL,
    z                   REAL NOT NULL,
    name                VARCHAR(755),
    CONSTRAINT location_name_length CHECK (name IS NULL OR char_length(name) <= 755)
);

CREATE TABLE IF NOT EXISTS routes (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    coordinate_x        DOUBLE PRECISION NOT NULL,
    coordinate_y        BIGINT NOT NULL,
    creation_date       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    from_location_id    INTEGER NOT NULL REFERENCES locations(id),
    to_location_id      INTEGER REFERENCES locations(id),
    distance            REAL NOT NULL,
    rating              INTEGER NOT NULL,
    CONSTRAINT route_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT route_distance_valid CHECK (distance > 1),
    CONSTRAINT route_rating_positive CHECK (rating > 0)
);

-- Позволяет продемонстрировать корректное переназначение связанных объектов при удалении.
CREATE TABLE IF NOT EXISTS route_links (
    source_route_id     INTEGER NOT NULL REFERENCES routes(id) ON DELETE CASCADE,
    related_route_id    INTEGER NOT NULL REFERENCES routes(id) ON DELETE RESTRICT,
    PRIMARY KEY (source_route_id, related_route_id),
    CONSTRAINT route_link_not_self CHECK (source_route_id <> related_route_id)
);

CREATE INDEX IF NOT EXISTS routes_name_lower_idx ON routes (lower(name));
CREATE INDEX IF NOT EXISTS routes_rating_idx ON routes (rating);
CREATE INDEX IF NOT EXISTS routes_locations_idx ON routes (from_location_id, to_location_id);

CREATE OR REPLACE FUNCTION delete_route_with_replacement(p_route_id INTEGER, p_replacement_id INTEGER)
RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM routes WHERE id = p_route_id) THEN
        RAISE EXCEPTION 'Маршрут % не найден', p_route_id;
    END IF;
    IF p_replacement_id = p_route_id THEN
        RAISE EXCEPTION 'Маршрут не может заменять сам себя';
    END IF;
    IF p_replacement_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM routes WHERE id = p_replacement_id) THEN
        RAISE EXCEPTION 'Маршрут-замена % не найден', p_replacement_id;
    END IF;
    IF p_replacement_id IS NULL AND EXISTS (SELECT 1 FROM route_links WHERE related_route_id = p_route_id) THEN
        RAISE EXCEPTION 'Выберите маршрут-замену: на удаляемый объект есть ссылки';
    END IF;
    IF p_replacement_id IS NOT NULL THEN
        INSERT INTO route_links(source_route_id, related_route_id)
        SELECT source_route_id, p_replacement_id FROM route_links
        WHERE related_route_id = p_route_id AND source_route_id <> p_replacement_id
        ON CONFLICT DO NOTHING;
        DELETE FROM route_links WHERE related_route_id = p_route_id;
    END IF;
    DELETE FROM routes WHERE id = p_route_id;
END;
$$;

CREATE OR REPLACE FUNCTION delete_one_route_by_rating(p_rating INTEGER)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_id INTEGER; v_replacement INTEGER;
BEGIN
    SELECT id INTO v_id FROM routes WHERE rating = p_rating ORDER BY id LIMIT 1 FOR UPDATE;
    IF v_id IS NOT NULL THEN
        SELECT id INTO v_replacement FROM routes WHERE id <> v_id ORDER BY id LIMIT 1;
        PERFORM delete_route_with_replacement(v_id, v_replacement);
    END IF;
    RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION max_rating_route()
RETURNS SETOF routes LANGUAGE sql STABLE AS $$
    SELECT * FROM routes ORDER BY rating DESC, id ASC LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION routes_rating_less_than(p_rating INTEGER)
RETURNS SETOF routes LANGUAGE sql STABLE AS $$
    SELECT * FROM routes WHERE rating < p_rating ORDER BY rating DESC, id;
$$;

CREATE OR REPLACE FUNCTION find_routes_between(p_from INTEGER, p_to INTEGER, p_sort TEXT)
RETURNS SETOF routes LANGUAGE plpgsql STABLE AS $$
BEGIN
    IF p_sort NOT IN ('name', 'rating', 'distance', 'creation_date') THEN
        RAISE EXCEPTION 'Недопустимый параметр сортировки: %', p_sort;
    END IF;
    RETURN QUERY EXECUTE format(
        'SELECT * FROM routes WHERE from_location_id = $1 AND to_location_id = $2 ORDER BY %I, id', p_sort
    ) USING p_from, p_to;
END;
$$;

CREATE OR REPLACE FUNCTION add_route_between(
    p_name TEXT, p_coordinate_x DOUBLE PRECISION, p_coordinate_y BIGINT,
    p_from INTEGER, p_to INTEGER, p_distance REAL, p_rating INTEGER
) RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_id INTEGER;
BEGIN
    IF p_name IS NULL OR btrim(p_name) = '' THEN RAISE EXCEPTION 'Название не может быть пустым'; END IF;
    IF p_distance <= 1 THEN RAISE EXCEPTION 'Расстояние должно быть больше 1'; END IF;
    IF p_rating <= 0 THEN RAISE EXCEPTION 'Рейтинг должен быть больше 0'; END IF;
    INSERT INTO routes(name, coordinate_x, coordinate_y, from_location_id, to_location_id, distance, rating)
    VALUES (btrim(p_name), p_coordinate_x, p_coordinate_y, p_from, p_to, p_distance, p_rating)
    RETURNING id INTO v_id;
    RETURN v_id;
END;
$$;
